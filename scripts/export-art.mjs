// Regenerates the bundled PNG art from the procedural source:
//   src/assets/images/<asset id>.png, src/assets/sheets/<sheet id>.png, src/assets/textures/<terrain>.png
// plus src/assets/manifest.json. Usage: npm run art:export
// Needs a Chromium for playwright-core (PLAYWRIGHT_BROWSERS_PATH, or CHROMIUM_PATH=/path/to/chrome).
import { createServer } from 'vite';
import { chromium } from 'playwright-core';
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import { statSync } from 'node:fs';

const root = resolve(import.meta.dirname, '..');
const server = await createServer({ root, logLevel: 'error', server: { port: 0, host: '127.0.0.1' } });
await server.listen();
const url = server.resolvedUrls.local[0];
const browser = await chromium.launch(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {});
try {
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.goto(new URL('tools/export-art.html', url).href);
  await page.waitForFunction(() => typeof window.__exportArt === 'function', null, { timeout: 30000 });
  const files = await page.evaluate(() => window.__exportArt());
  if (errors.length) throw new Error(errors.join('\n'));
  const manifest = { note: 'Generated by npm run art:export from the procedural art. Files may be repainted by hand (keep the same size).', images: [], sheets: [], textures: [] };
  for (const dir of ['images', 'sheets', 'textures']) {
    const d = join(root, 'src/assets', dir);
    mkdirSync(d, { recursive: true });
    for (const f of readdirSync(d)) if (f.endsWith('.png')) rmSync(join(d, f));
  }
  let bytes = 0;
  for (const f of files) {
    const buf = Buffer.from(f.data.replace(/^data:image\/png;base64,/, ''), 'base64');
    bytes += buf.length;
    writeFileSync(join(root, 'src/assets', f.dir, `${f.name}.png`), buf);
    manifest[f.dir].push({ id: f.name, file: `${f.dir}/${f.name}.png`, width: f.w, height: f.h, bytes: buf.length, ...f.meta });
  }
  // optional palette quantization (much smaller files, visually identical for this flat art)
  const paths = files.map((f) => join(root, 'src/assets', f.dir, `${f.name}.png`));
  const q = process.env.NO_QUANTIZE ? { status: 1 } : spawnSync('python3', [join(root, 'scripts/quantize-png.py'), ...paths], { stdio: 'inherit' });
  if (q.status === 0) {
    bytes = 0;
    for (const dir of ['images', 'sheets', 'textures']) for (const m of manifest[dir]) bytes += m.bytes = statSync(join(root, 'src/assets', m.file)).size;
  } else console.log('(palette quantization skipped: needs python3 + Pillow)');
  writeFileSync(join(root, 'src/assets/manifest.json'), JSON.stringify(manifest, null, 1) + '\n');
  console.log(`wrote ${manifest.images.length} sprites, ${manifest.sheets.length} sheets, ${manifest.textures.length} textures (${(bytes / 1024 / 1024).toFixed(2)} MB)`);
} finally {
  await browser.close();
  await server.close();
}
